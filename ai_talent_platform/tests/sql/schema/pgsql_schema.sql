CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE public.dim_organization (
	org_id BIGINT NOT NULL, 
	code VARCHAR(64) NOT NULL, 
	name VARCHAR(128) NOT NULL, 
	level INTEGER NOT NULL, 
	path VARCHAR(512) NOT NULL, 
	parent_id BIGINT, 
	synced_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_dim_organization PRIMARY KEY (org_id), 
	CONSTRAINT uq_dim_organization_code UNIQUE (code), 
	CONSTRAINT ck_dim_organization_level_positive CHECK (level >= 1)
);

CREATE INDEX ix_dim_organization_parent ON public.dim_organization (parent_id);

CREATE TABLE public.dim_talent_wide (
	talent_id BIGINT NOT NULL, 
	name VARCHAR(64) NOT NULL, 
	org_path VARCHAR(512), 
	education VARCHAR(32), 
	work_years NUMERIC(5, 2), 
	skill_tags TEXT[] DEFAULT '{}'::text[] NOT NULL, 
	potential_level VARCHAR(32), 
	match_avg_score NUMERIC(5, 2), 
	synced_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_dim_talent_wide PRIMARY KEY (talent_id), 
	CONSTRAINT ck_dim_talent_wide_work_years_non_negative CHECK (work_years IS NULL OR work_years >= 0), 
	CONSTRAINT ck_dim_talent_wide_match_score_range CHECK (match_avg_score IS NULL OR (match_avg_score >= 0 AND match_avg_score <= 100))
);

CREATE INDEX ix_dim_talent_wide_education ON public.dim_talent_wide (education);

CREATE INDEX ix_dim_talent_wide_potential ON public.dim_talent_wide (potential_level);

CREATE TABLE public.fact_assessment_history (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	assessment_id BIGINT NOT NULL, 
	talent_id BIGINT NOT NULL, 
	position_id BIGINT, 
	total_score NUMERIC(5, 2), 
	level VARCHAR(32), 
	dimension_scores JSONB DEFAULT '{}'::jsonb NOT NULL, 
	scored_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_fact_assessment_history PRIMARY KEY (id, scored_at), 
	CONSTRAINT ck_fact_assessment_history_score_range CHECK (total_score IS NULL OR (total_score >= 0 AND total_score <= 100))
)
 PARTITION BY RANGE (scored_at);

CREATE INDEX ix_fact_assessment_history_assessment ON public.fact_assessment_history (assessment_id);

CREATE INDEX ix_fact_assessment_history_talent_time ON public.fact_assessment_history (talent_id, scored_at);

CREATE TABLE public.fact_behavior_event (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	talent_id BIGINT NOT NULL, 
	event_type VARCHAR(64) NOT NULL, 
	page VARCHAR(512), 
	duration_ms INTEGER, 
	event_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_fact_behavior_event PRIMARY KEY (id, event_at), 
	CONSTRAINT ck_fact_behavior_event_duration_non_negative CHECK (duration_ms IS NULL OR duration_ms >= 0)
)
 PARTITION BY RANGE (event_at);

CREATE INDEX ix_fact_behavior_event_talent_time ON public.fact_behavior_event (talent_id, event_at);

CREATE INDEX ix_fact_behavior_event_type_time ON public.fact_behavior_event (event_type, event_at);

CREATE TABLE public.fact_talent_snapshot (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	snapshot_month DATE NOT NULL, 
	organization_id BIGINT NOT NULL, 
	education VARCHAR(32) DEFAULT '' NOT NULL, 
	age_group VARCHAR(32) DEFAULT '' NOT NULL, 
	talent_count INTEGER DEFAULT 0 NOT NULL, 
	avg_work_years NUMERIC(5, 2), 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_fact_talent_snapshot PRIMARY KEY (id, snapshot_month), 
	CONSTRAINT uq_fact_talent_snapshot_dimensions UNIQUE (snapshot_month, organization_id, education, age_group), 
	CONSTRAINT ck_fact_talent_snapshot_count_non_negative CHECK (talent_count >= 0), 
	CONSTRAINT ck_fact_talent_snapshot_work_years_non_negative CHECK (avg_work_years IS NULL OR avg_work_years >= 0)
)
 PARTITION BY RANGE (snapshot_month);

CREATE INDEX ix_fact_talent_snapshot_org_month ON public.fact_talent_snapshot (organization_id, snapshot_month);

CREATE TABLE public.fact_training_track (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	talent_id BIGINT NOT NULL, 
	course_id BIGINT NOT NULL, 
	plan_id BIGINT, 
	progress NUMERIC(5, 2) DEFAULT 0 NOT NULL, 
	study_minutes INTEGER DEFAULT 0 NOT NULL, 
	status VARCHAR(32) NOT NULL, 
	event_at TIMESTAMP WITH TIME ZONE NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	CONSTRAINT pk_fact_training_track PRIMARY KEY (id, event_at), 
	CONSTRAINT ck_fact_training_track_progress_range CHECK (progress >= 0 AND progress <= 100), 
	CONSTRAINT ck_fact_training_track_minutes_non_negative CHECK (study_minutes >= 0)
)
 PARTITION BY RANGE (event_at);

CREATE INDEX ix_fact_training_track_course ON public.fact_training_track (course_id);

CREATE INDEX ix_fact_training_track_talent_time ON public.fact_training_track (talent_id, event_at);

CREATE TABLE IF NOT EXISTS public.fact_talent_snapshot_default PARTITION OF public.fact_talent_snapshot DEFAULT;

CREATE TABLE IF NOT EXISTS public.fact_assessment_history_default PARTITION OF public.fact_assessment_history DEFAULT;

CREATE TABLE IF NOT EXISTS public.fact_training_track_default PARTITION OF public.fact_training_track DEFAULT;

CREATE TABLE IF NOT EXISTS public.fact_behavior_event_default PARTITION OF public.fact_behavior_event DEFAULT;

