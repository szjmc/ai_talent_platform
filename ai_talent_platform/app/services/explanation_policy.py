"""
功能：拦截解释自行增加的业务规则。
输入：待检查文本。
输出：是否包含未授权规则表达。
流程：识别阈值、及格线、录用概率等规则词。
边界：当前证据契约没有正式阈值配置；不是通用自然语言事实校验。

标签：[Agent组] [P1]（匹配解释的表述策略）
"""
import re

_RULE = re.compile(r"阈值|及格线|合格线|录用概率|录用率|录用门槛|通过线|threshold|cutoff", re.I)

def unsupported_rule(text: str) -> bool:
    """当前证据契约不含正式阈值配置，涉及阈值决策的表述一律拒绝。

    不用“数字恰好在证据里”证明规则获授权，避免0.7来源混淆。
    普通“完整度为50%”不属于阈值规则，继续由其他校验器处理。
    """
    return bool(_RULE.search(text))
